"""
One command builds the whole profile from profile.json + a photo:

  python scripts/build.py --photo path/to/photo.jpg [--config profile.json] [--out DIR]

Writes into DIR (default: repo root):
  assets/contrib-heatmap.svg  assets/ascii-portrait.svg  assets/info-card.svg
  data/contributions.json     README.md                  .github/workflows/snake.yml
The photo itself is never copied into the output.
"""
import argparse
import importlib
import os
import shutil
import sys
import xml.dom.minidom
from urllib.parse import quote
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from config import ROOT, load  # noqa: E402

BADGES = {  # key -> (label, colour, logo, url template)
    "email": ("Email", "0d1117", "gmail", "mailto:{v}"),
    "instagram": ("Instagram", "E4405F", "instagram", "https://instagram.com/{v}"),
    "linkedin": ("LinkedIn", "0A66C2", "linkedin", "https://linkedin.com/in/{v}"),
    "x": ("X", "000000", "x", "https://x.com/{v}"),
    "youtube": ("YouTube", "FF0000", "youtube", "https://youtube.com/@{v}"),
    "website": ("Website", "0d1117", "googlechrome", "{v}"),
}


def badge(key, value):
    label, colour, logo, url = BADGES[key]
    value = value.strip().lstrip("@")
    shown = value.split("@")[0] if key == "email" else value.replace("https://", "").replace("http://", "").rstrip("/")
    shown = shown.replace("-", "--").replace("_", "__")           # shields.io escaping
    href = value if value.startswith("http") else url.format(v=value)
    img = (f"https://img.shields.io/badge/{quote(label)}-{quote(shown)}-{colour}"
           f"?style=for-the-badge&logo={logo}&logoColor=white")
    return f'<a href="{escape(href)}"><img src="{escape(img)}" alt="{label}"/></a>'


def readme(cfg):
    u, h = cfg["github_username"], cfg["handle"]
    links = "\n".join(badge(k, v) for k, v in cfg.get("links", {}).items() if k in BADGES and str(v).strip())
    snake = f"https://raw.githubusercontent.com/{u}/{u}/output"
    credit = "" if u.lower() == "gubreleysanskar" else \
        '\n<sub>Profile template by <a href="https://github.com/GubreleySanskar">@GubreleySanskar</a></sub>\n'

    return f"""<div align="center">

<!-- generated by scripts/build.py from profile.json -->

<h3><code>~/{h} $ ./contributions.sh</code></h3>

<img src="./assets/contrib-heatmap.svg" width="860" alt="Contribution graph"/>

<br><br>

<h3><code>~/{h} $ whoami</code></h3>

<table>
  <tr>
    <td valign="top"><img src="./assets/ascii-portrait.svg" width="370" alt="ASCII portrait of {escape(cfg['name'])}"/></td>
    <td valign="top"><img src="./assets/info-card.svg" width="490" alt="{escape(cfg['name'])} · {escape(cfg['tagline'])}"/></td>
  </tr>
</table>

<br>

<h3><code>~/{h} $ ./snake --eat contributions</code></h3>

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="{snake}/github-snake-dark.svg"/>
  <source media="(prefers-color-scheme: light)" srcset="{snake}/github-snake.svg"/>
  <img width="860" alt="snake eating the contribution graph" src="{snake}/github-snake.svg"/>
</picture>

<br><br>

<h3><code>~/{h} $ ./links.sh</code></h3>

<p><b>{escape(cfg.get('headline') or cfg['tagline'])}</b></p>

{links}

<br>
{credit}
</div>
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--photo", required=True)
    ap.add_argument("--out", default=ROOT)
    ap.add_argument("--config", help="profile.json to use (default: repo root)")
    a = ap.parse_args()
    if a.config:
        os.environ["PROFILE_JSON"] = os.path.abspath(a.config)
    cfg = load()
    out = os.path.abspath(a.out)
    for d in ("assets", "data", ".github/workflows"):
        os.makedirs(os.path.join(out, d), exist_ok=True)

    # 1. heatmap + data (the card's stat tiles read this)
    hm = importlib.import_module("make_heatmap")
    data = hm.make_data()
    st = hm.stats(data)
    import json
    json.dump({"stats": st, "days": [[d.isoformat(), c] for d, c in data]},
              open(os.path.join(out, "data", "contributions.json"), "w"), indent=1)
    os.environ["CONTRIB_JSON"] = os.path.join(out, "data", "contributions.json")
    open(os.path.join(out, "assets", "contrib-heatmap.svg"), "w").write(hm.svg(data, st))

    # 2. portrait + card, both windows the same height
    pt = importlib.import_module("make_ascii_portrait")
    lines = pt.to_ascii(*pt.prep(a.photo))
    natural = round(pt.TOP + len(lines) * pt.LINE_H + pt.BOTTOM)
    ic = importlib.import_module("make_info_card")
    _, card_need = ic.card(natural)
    height = max(natural, card_need)
    os.environ["MIN_H"] = str(height)
    open(os.path.join(out, "assets", "ascii-portrait.svg"), "w").write(pt.svg(lines))
    card_svg, _ = ic.card(height)
    open(os.path.join(out, "assets", "info-card.svg"), "w").write(card_svg)

    # 3. README + snake workflow
    open(os.path.join(out, "README.md"), "w").write(readme(cfg))
    wf_src = os.path.join(ROOT, ".github", "workflows", "snake.yml")
    wf_dst = os.path.join(out, ".github", "workflows", "snake.yml")
    if os.path.abspath(wf_src) != os.path.abspath(wf_dst):
        shutil.copy(wf_src, wf_dst)

    for f in ("contrib-heatmap.svg", "ascii-portrait.svg", "info-card.svg"):
        xml.dom.minidom.parse(os.path.join(out, "assets", f))     # fail loudly on broken SVG
    print(f"built profile for {cfg['github_username']} in {out}")
    print(f"  portrait {len(lines)} rows, windows {height}px tall, heatmap {st['total']} contributions")


if __name__ == "__main__":
    main()
